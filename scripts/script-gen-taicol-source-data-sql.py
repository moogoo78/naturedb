"""Generate SQL that loads a TaiCOL taxon export into taxon.source_data of
taxon tree 2 (TaiCOL).

The SQL (one transaction):
  1. loads the CSV rows into a temp table (row -> jsonb, empty cells dropped,
     plus "_release": <YYYYMMDD from the file name>)
  2. taxa that already carry a TaiCOL source_id get source_data = their row
  3. major-rank taxa (kingdom..genus) built from lineage columns have no
     source_id: they are matched by (rank, name) to a TaiCOL row not used by
     another taxon; homonyms (same genus name in two kingdoms) are resolved by
     the taxon's kingdom ancestor. Only unique matches are written, so they
     also get their TaiCOL taxon_id as source_id.

Names, authors, common names and the tree structure are NOT changed; the
summary printed at the end of the SQL shows what is left unmatched.

Taxa are resolved by source_id / name inside tree 2, never by local id, so
the same file runs on dev and prod. Re-running is a no-op (same values).

usage (host, no app imports needed):
    python3 scripts/script-gen-taicol-source-data-sql.py \
        taicol/TaiCOL_taxon_20261030.csv > scripts/sql/taicol-source-data-20261030.sql
"""
import csv
import json
import re
import sys

TREE_ID = 2
MAJOR_RANKS = ('kingdom', 'phylum', 'class', 'order', 'family', 'genus')
BATCH = 500


def q(s):
    return "'" + s.replace("'", "''") + "'"


def main(path):
    m = re.search(r'(\d{8})', path)
    release = m.group(1) if m else None

    with open(path, encoding='utf-8-sig', newline='') as f:
        rows = list(csv.DictReader(f))

    out = sys.stdout
    out.write(f'-- generated by scripts/script-gen-taicol-source-data-sql.py from {path}\n')
    out.write(f'-- {len(rows)} TaiCOL rows, release {release}\n')
    out.write('BEGIN;\n')
    # Parallel hash joins allocate /dev/shm segments; Docker's default 64MB
    # shm is too small for this batch ("could not resize shared memory").
    out.write('SET LOCAL max_parallel_workers_per_gather = 0;\n\n')
    out.write('CREATE TEMP TABLE taicol_csv (\n'
              '    taxon_id text PRIMARY KEY, rank text, simple_name text, kingdom text, data jsonb\n'
              ') ON COMMIT DROP;\n\n')

    for i in range(0, len(rows), BATCH):
        values = []
        for r in rows[i:i + BATCH]:
            data = {k: v for k, v in r.items() if k and v != ''}
            if release:
                data['_release'] = release
            values.append('({}, {}, {}, {}, {}::jsonb)'.format(
                q(r['taxon_id']), q(r['rank'].lower()), q(r['simple_name']),
                q(r['kingdom']) if r['kingdom'] else 'NULL',
                q(json.dumps(data, ensure_ascii=False, separators=(',', ':'))),
            ))
        out.write('INSERT INTO taicol_csv VALUES\n' + ',\n'.join(values) + ';\n')

    majors = ', '.join(q(x) for x in MAJOR_RANKS)
    out.write(f'''
ANALYZE taicol_csv;

-- 1. taxa that already carry a TaiCOL taxon_id
UPDATE taxon t SET source_data = c.data
FROM taicol_csv c
WHERE t.tree_id = {TREE_ID} AND t.source_id = c.taxon_id
  AND t.source_data IS DISTINCT FROM c.data;

-- 2. major ranks without source_id: match by (rank, name), kingdom breaks ties
WITH free AS (
    SELECT c.* FROM taicol_csv c
    WHERE c.rank IN ({majors})
      AND NOT EXISTS (SELECT 1 FROM taxon x WHERE x.tree_id = {TREE_ID} AND x.source_id = c.taxon_id)
), tk AS (
    SELECT t.id, t.rank, t.canonical_name,
           CASE WHEN t.rank = 'kingdom' THEN t.canonical_name ELSE (
               SELECT k.canonical_name FROM taxon_relation r JOIN taxon k ON k.id = r.parent_id
               WHERE r.child_id = t.id AND k.rank = 'kingdom' AND k.tree_id = {TREE_ID} LIMIT 1
           ) END AS kingdom
    FROM taxon t
    WHERE t.tree_id = {TREE_ID} AND t.source_id IS NULL AND t.rank IN ({majors})
), cand AS (
    SELECT tk.id, f.taxon_id, f.data,
           f.kingdom IS NOT DISTINCT FROM tk.kingdom AS same_kingdom,
           count(*) OVER (PARTITION BY tk.id) AS n,
           count(*) FILTER (WHERE f.kingdom IS NOT DISTINCT FROM tk.kingdom) OVER (PARTITION BY tk.id) AS n_kingdom
    FROM tk JOIN free f ON f.rank = tk.rank AND f.simple_name = tk.canonical_name
), pick AS (
    SELECT id, taxon_id, data FROM cand WHERE n = 1 OR (n_kingdom = 1 AND same_kingdom)
), uniq AS (
    -- never give one TaiCOL taxon_id to two local taxa
    SELECT * FROM (SELECT *, count(*) OVER (PARTITION BY taxon_id) AS used FROM pick) p WHERE used = 1
)
UPDATE taxon t SET source_id = u.taxon_id, source_data = u.data
FROM uniq u WHERE t.id = u.id;

-- summary
SELECT 'tree {TREE_ID} with source_data' AS what, count(*) FROM taxon WHERE tree_id = {TREE_ID} AND source_data ? '_release'
UNION ALL SELECT 'source_id not in this release', count(*) FROM taxon t
    WHERE t.tree_id = {TREE_ID} AND t.source_id IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM taicol_csv c WHERE c.taxon_id = t.source_id)
UNION ALL SELECT 'major rank still without source_id', count(*) FROM taxon
    WHERE tree_id = {TREE_ID} AND source_id IS NULL AND rank IN ({majors})
UNION ALL SELECT 'TaiCOL rows not in tree', count(*) FROM taicol_csv c
    WHERE NOT EXISTS (SELECT 1 FROM taxon x WHERE x.tree_id = {TREE_ID} AND x.source_id = c.taxon_id);

COMMIT;
''')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
