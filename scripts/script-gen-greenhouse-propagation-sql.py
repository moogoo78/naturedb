"""Generate SQL that imports basdb greenhouse propagations
(<basdb_export_dir>/greenhouse_propagation.csv, from greenhouse_propagation in a
basdb dump) into unit_relationship.

A basdb propagation is a dated event on one plant (type, date, note): e.g. seeds
harvested and stored. Each becomes
    unit_id                   naturedb unit whose source_data->'basdb'->>'id' is
                              the basdb unit_id (collection 'greenhouse')
    related_unit_id           NULL (no other unit involved)
    relationship_of_resource  'propagation'
    established_date          date
    remarks                   'type: note', or 'type' (same as migration
                              c5d7e9f1a3b4 for the old propagation table)
    created / updated         basdb created, in naturedb's local time (UTC+8)

All rows are in the SQL; only those whose basdb unit is in naturedb are inserted
(today the dataset-2 units). Rows on basdb units that are not imported (dataset 1,
the legacy seed list) are counted and left out, so rerunning the file after such
units are imported picks them up. Idempotent: a row is skipped when the unit
already has a propagation with the same date and remarks.

Prerequisites on the target DB: migration c5d7e9f1a3b4 (unit_relationship) and the
greenhouse unit imports (greenhouse-units-ds2.sql, greenhouse-units-uncovered.sql).

usage:
    python3 scripts/script-gen-greenhouse-propagation-sql.py <basdb_export_dir> \
        > scripts/sql/greenhouse-propagation.sql
"""
import csv
import sys
from pathlib import Path


def q(s):
    return 'NULL' if s in (None, '') else "'" + str(s).replace("'", "''") + "'"


def remarks(row):
    return ': '.join(x for x in (row['type_field'].strip(), row['note'].strip()) if x)


def main(export_dir):
    with open(Path(export_dir) / 'greenhouse_propagation.csv', newline='', encoding='utf-8') as fh:
        rows = list(csv.DictReader(fh))

    values = ',\n'.join(
        f"    ({int(r['id'])}, {int(r['unit_id']) if r['unit_id'] else 'NULL'}, "
        f"{q(r['date'])}::date, {q(remarks(r))}, {q(r['created'])}::timestamptz)"
        for r in rows
    )
    print(f'''-- generated by scripts/script-gen-greenhouse-propagation-sql.py: {len(rows)} basdb propagations
BEGIN;

DO $$ BEGIN
  IF to_regclass('unit_relationship') IS NULL THEN
    RAISE EXCEPTION 'unit_relationship is missing: run alembic upgrade (c5d7e9f1a3b4) first';
  END IF;
  IF (SELECT id FROM collection WHERE name = 'greenhouse') IS NULL THEN
    RAISE EXCEPTION 'collection greenhouse is missing';
  END IF;
END $$;

CREATE TEMP TABLE _prop (basdb_id int, basdb_unit_id int, date date, remarks text, created timestamptz) ON COMMIT DROP;
INSERT INTO _prop VALUES
{values};

CREATE TEMP TABLE _unit ON COMMIT DROP AS
SELECT DISTINCT ON ((u.source_data->'basdb'->>'id')::int) (u.source_data->'basdb'->>'id')::int AS basdb_unit_id, u.id AS unit_id
FROM unit u
WHERE u.collection_id = (SELECT id FROM collection WHERE name = 'greenhouse')
  AND u.source_data->'basdb'->>'id' ~ '^[0-9]+$'
ORDER BY (u.source_data->'basdb'->>'id')::int, u.id;

DO $$
DECLARE n_unit int; n_new int;
BEGIN
  SELECT count(*), count(*) FILTER (WHERE NOT EXISTS (
           SELECT 1 FROM unit_relationship r
           WHERE r.unit_id = u.unit_id AND r.relationship_of_resource = 'propagation'
             AND r.established_date IS NOT DISTINCT FROM p.date AND r.remarks IS NOT DISTINCT FROM p.remarks))
    INTO n_unit, n_new
    FROM _prop p JOIN _unit u USING (basdb_unit_id);
  RAISE NOTICE 'basdb propagations: % total, % on a naturedb unit (% new), % on basdb units not in naturedb',
    (SELECT count(*) FROM _prop), n_unit, n_new, (SELECT count(*) FROM _prop) - n_unit;
END $$;

INSERT INTO unit_relationship (unit_id, related_unit_id, relationship_of_resource, established_date, remarks, created, updated)
SELECT u.unit_id, NULL, 'propagation', p.date, p.remarks,
       p.created AT TIME ZONE 'Asia/Taipei', p.created AT TIME ZONE 'Asia/Taipei'
FROM _prop p
JOIN _unit u USING (basdb_unit_id)
WHERE NOT EXISTS (
    SELECT 1 FROM unit_relationship r
    WHERE r.unit_id = u.unit_id AND r.relationship_of_resource = 'propagation'
      AND r.established_date IS NOT DISTINCT FROM p.date AND r.remarks IS NOT DISTINCT FROM p.remarks
)
ORDER BY p.basdb_id;

COMMIT;''')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
