"""Generate SQL that points the imported basdb greenhouse images at their
resized copies in s3://brmas-hast/greenhouse/ (rendered and named by
scripts/script-render-greenhouse-images.py, uploaded by hand):

    file_url  https://brmas-begonia.s3.../<basdb name>.jpg
           -> https://brmas-hast.s3.ap-northeast-1.amazonaws.com/greenhouse/{uuid}-m.jpg

The -m file is the stored URL, as for an admin upload; clients switch to the
-s/-l/-x/-o sizes by replacing '-m.jpg'. The new key is recorded in
source_data->'basdb'->'rehost'; the old basdb key stays in aws_s3_path.

Rows are matched on source_data->'basdb'->>'id' in collection 'greenhouse' and
only updated while file_url is still the brmas-begonia URL: idempotent, and a
file_url changed by hand is left alone. Names do not depend on the database, so
the same file serves dev and prod.

Prerequisite on the target DB: scripts/sql/greenhouse-unit-images.sql.
Upload before running it: an updated file_url that is not in the bucket is a
broken image.

usage:
    python3 scripts/script-gen-greenhouse-images-rehost-sql.py <basdb_export_dir> \
        > scripts/sql/greenhouse-images-rehost.sql
"""
import csv
import sys
from pathlib import Path

BASE_URL = 'https://brmas-hast.s3.ap-northeast-1.amazonaws.com/greenhouse/'


def main(export_dir):
    with open(Path(export_dir) / 'greenhouse_unitimage-rehost.csv', newline='', encoding='utf-8') as fh:
        rows = list(csv.DictReader(fh))
    values = ',\n'.join(f"  ({int(r['basdb_image_id'])}, '{r['uuid']}'::uuid)" for r in rows)
    print(f'''-- generated by scripts/script-gen-greenhouse-images-rehost-sql.py: {len(rows)} basdb images
-- file_url -> {BASE_URL}{{uuid}}-m.jpg (upload the rendered files first)
-- run:  psql -v ON_ERROR_STOP=1 -U $POSTGRES_USER -d $POSTGRES_DB -f greenhouse-images-rehost.sql
BEGIN;

DO $$ BEGIN
  IF (SELECT id FROM collection WHERE name = 'greenhouse') IS NULL THEN
    RAISE EXCEPTION 'collection greenhouse is missing';
  END IF;
END $$;

CREATE TEMP TABLE _rehost (basdb_image_id int PRIMARY KEY, uuid uuid) ON COMMIT DROP;
INSERT INTO _rehost VALUES
{values};

CREATE TEMP TABLE _match ON COMMIT DROP AS
SELECT m.id, r.uuid, m.file_url LIKE 'https://brmas-begonia.s3.%' AS on_basdb
FROM multimedia_object m
JOIN unit u ON u.id = m.unit_id
JOIN _rehost r ON r.basdb_image_id = (m.source_data->'basdb'->>'id')::int
WHERE u.collection_id = (SELECT id FROM collection WHERE name = 'greenhouse')
  AND m.source_data->'basdb' IS NOT NULL;

UPDATE multimedia_object m
SET file_url = '{BASE_URL}' || x.uuid || '-m.jpg',
    source_data = jsonb_set(m.source_data, '{{basdb,rehost}}', to_jsonb('brmas-hast/greenhouse/' || x.uuid || '-m.jpg')),
    updated = now() AT TIME ZONE 'Asia/Taipei'
FROM _match x
WHERE m.id = x.id AND x.on_basdb;

DO $$
DECLARE n_src int; n_match int; n_new int;
BEGIN
  SELECT count(*) INTO n_src FROM _rehost;
  SELECT count(*), count(*) FILTER (WHERE on_basdb) INTO n_match, n_new FROM _match;
  RAISE NOTICE 'rehost: % images, % in this database, % repointed now, % already repointed or changed by hand',
    n_src, n_match, n_new, n_match - n_new;
END $$;

COMMIT;''')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
