"""Generate SQL that imports basdb greenhouse unit images (greenhouse_unitimage)
into naturedb multimedia_object, attached to the units imported by
scripts/sql/greenhouse-units-ds2.sql (unit.source_data->'basdb'->>'id').

The images stay where basdb uploaded them (public-read objects in
s3://brmas-begonia), so file_url points there. They are single full-size
files, not naturedb's -s/-m/-l/-x/-o set: the '-m.jpg' replace in naturedb is a
no-op for them, so every size falls back to the original. The S3 key and the
basdb row are kept in source_data->'basdb' to re-point file_url if the images
are later moved into brmas-media.

Images skipped:
  - no S3 object (s3_size empty: aws_s3_path missing from the bucket)
  - basdb unit_id empty, or the unit is not in naturedb (checked in SQL)

input <basdb_export_dir>/greenhouse_unitimage.csv:
    id,file_field,position,unit_id,aws_s3_path,s3_size
    (greenhouse_unitimage + the object size from `aws s3 ls s3://brmas-begonia`)

Prerequisites on the target DB:
  1. scripts/sql/greenhouse-collection.sql
  2. scripts/sql/greenhouse-units-ds2.sql

usage:
    python3 scripts/script-gen-greenhouse-unit-images-sql.py <basdb_export_dir> \
        > scripts/sql/greenhouse-unit-images.sql
"""
import csv
import json
import sys

BASE_URL = 'https://brmas-begonia.s3.ap-northeast-1.amazonaws.com/'


def q(s):
    return 'NULL' if s in (None, '') else "'" + str(s).replace("'", "''") + "'"


def main(export_dir):
    rows, no_s3, no_unit = [], 0, 0
    for r in csv.DictReader(open(f'{export_dir}/greenhouse_unitimage.csv')):
        if not r['unit_id']:
            no_unit += 1
            continue
        if not r['s3_size']:
            no_s3 += 1
            continue
        sd = {'basdb': {
            'id': int(r['id']),
            'unit_id': int(r['unit_id']),
            'position': int(r['position']),
            'file_field': r['file_field'] or None,
            'aws_s3_path': r['aws_s3_path'],
            's3_bucket': 'brmas-begonia',
            's3_size': int(r['s3_size']),
        }}
        rows.append((int(r['id']), int(r['unit_id']), int(r['position']),
                     BASE_URL + r['aws_s3_path'], json.dumps(sd, ensure_ascii=False)))
    rows.sort(key=lambda x: (x[1], x[2], x[0]))

    w = sys.stdout.write
    w(f'''-- Import basdb greenhouse unit images into multimedia_object (collection 'greenhouse')
-- generated by scripts/script-gen-greenhouse-unit-images-sql.py from basdb export
-- images: {len(rows)} with an S3 object; skipped in export: {no_s3} missing from S3, {no_unit} without unit
--
-- prerequisites: scripts/sql/greenhouse-collection.sql, scripts/sql/greenhouse-units-ds2.sql
-- idempotent: images already imported (multimedia_object.source_data->'basdb'->>'id') are skipped
-- run:  psql -v ON_ERROR_STOP=1 -U $POSTGRES_USER -d $POSTGRES_DB -f greenhouse-unit-images.sql

BEGIN;

CREATE TEMP TABLE _cfg ON COMMIT DROP AS
SELECT (SELECT id FROM collection WHERE name = 'greenhouse') AS collection_id,
  (SELECT id FROM multimedia_object_type WHERE title = 'StillImage') AS type_id,
  (SELECT id FROM multimedia_object_physical_format WHERE description = 'photograph') AS physical_format_id,
  (SELECT id FROM multimedia_object_context WHERE description = 'greenhouse living specimen') AS context_id;

DO $$
DECLARE c _cfg;
BEGIN
  SELECT * INTO c FROM _cfg;
  IF c.collection_id IS NULL THEN
    RAISE EXCEPTION 'collection greenhouse not found. Run scripts/sql/greenhouse-collection.sql first.';
  END IF;
  IF c.type_id IS NULL OR c.physical_format_id IS NULL OR c.context_id IS NULL THEN
    RAISE EXCEPTION 'multimedia_object type StillImage / physical format photograph / context greenhouse living specimen not found: %', c;
  END IF;
END $$;

-- multimedia_object.id lags behind rows inserted with explicit ids
SELECT setval(pg_get_serial_sequence('multimedia_object', 'id'), GREATEST((SELECT max(id) FROM multimedia_object), 1));

CREATE TEMP TABLE _src (
  basdb_image_id int, basdb_unit_id int, position int, file_url text, source_data jsonb
) ON COMMIT DROP;

INSERT INTO _src VALUES
''')
    w(',\n'.join(
        f'  ({iid}, {uid}, {pos}, {q(url)}, {q(sd)}::jsonb)'
        for iid, uid, pos, url, sd in rows) + ';\n')
    w(r'''
CREATE TEMP TABLE _basdb_unit ON COMMIT DROP AS
SELECT (source_data->'basdb'->>'id')::int AS basdb_unit_id, min(id) AS unit_id
FROM unit WHERE collection_id = (SELECT collection_id FROM _cfg) AND source_data->'basdb' IS NOT NULL
GROUP BY 1;

CREATE TEMP TABLE _res ON COMMIT DROP AS
SELECT s.*, b.unit_id
FROM _src s LEFT JOIN _basdb_unit b ON b.basdb_unit_id = s.basdb_unit_id;

CREATE TEMP TABLE _existing ON COMMIT DROP AS
SELECT (m.source_data->'basdb'->>'id')::int AS basdb_image_id
FROM multimedia_object m JOIN unit u ON u.id = m.unit_id
WHERE u.collection_id = (SELECT collection_id FROM _cfg) AND m.source_data->'basdb' IS NOT NULL;

INSERT INTO multimedia_object (
  created, updated, unit_id, file_url, source_data, type_id, physical_format_id, context_id
)
SELECT now() AT TIME ZONE 'Asia/Taipei', now() AT TIME ZONE 'Asia/Taipei',
  r.unit_id, r.file_url, r.source_data, c.type_id, c.physical_format_id, c.context_id
FROM _res r, _cfg c
WHERE r.unit_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM _existing e WHERE e.basdb_image_id = r.basdb_image_id)
ORDER BY r.unit_id, r.position, r.basdb_image_id;

DO $$
DECLARE n_src int; n_nounit int; n_skip int; n_total int; n_units int;
BEGIN
  SELECT count(*), count(*) FILTER (WHERE unit_id IS NULL) INTO n_src, n_nounit FROM _res;
  SELECT count(*) INTO n_skip FROM _existing e JOIN _src s ON s.basdb_image_id = e.basdb_image_id;
  SELECT count(*), count(DISTINCT m.unit_id) INTO n_total, n_units
    FROM multimedia_object m JOIN unit u ON u.id = m.unit_id
    WHERE u.collection_id = (SELECT collection_id FROM _cfg) AND m.source_data->'basdb' IS NOT NULL;
  RAISE NOTICE 'source images: %, unit not in naturedb: %, inserted now: %, already imported: %, greenhouse basdb images total: % on % units',
    n_src, n_nounit, n_src - n_nounit - n_skip, n_skip, n_total, n_units;
END $$;

COMMIT;
''')


if __name__ == '__main__':
    main(sys.argv[1])
